#[test]
fn intellij_triple_quote_cases() {
    let triple = "\"\"\"";
    let cases = [
        (
            format!("{triple}{triple}\nx={triple}{triple}"),
            &["STRING", "STATEMENT_BREAK", "LINE_BREAK", "IDENTIFIER", "=", "STRING", "STATEMENT_BREAK"][..],
        ),
        (format!("{triple}\\{triple} X \\{triple} {triple};"), &["STRING", ";", "STATEMENT_BREAK"]),
        (format!("{triple}\\nX\n\n{triple};"), &["STRING", ";", "STATEMENT_BREAK"]),
        ("x=''' X '\\''' X '''".to_owned(), &["IDENTIFIER", "=", "STRING", "STATEMENT_BREAK"]),
        (format!("x={triple} X \"\\{triple} X {triple}"), &["IDENTIFIER", "=", "STRING", "STATEMENT_BREAK"]),
        (format!("{triple} X {triple}\"\""), &["STRING", "STRING", "STATEMENT_BREAK"]),
    ];

    for (source, expected) in cases {
        assert_eq!(names(&source).as_slice(), expected, "source: {source:?}");
    }
}
