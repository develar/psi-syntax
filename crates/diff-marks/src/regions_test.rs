//! The regions a tool writes between two marker comments (`regions`) and the runs of their lines among the marks of a
//! pair (`marks::marks_of`): the forms of a marker, the markers that make no region, and what a change inside, across
//! and outside a region is to a reader.

use crate::bindings::{Bindings, NameQuestion, NamesAt};
use crate::marks::{marks_of, pair_grammar, pair_indented};
use crate::model::DiffMarks;
use crate::regions::{GeneratedRegion, generated_regions, region_of, with_generated};
use code_tokens::{Grammar, tokens};
use line_diff::model::{DiffBudget, LineDiff, LineRun, RunKind, diff_texts};
use line_diff::policy::WhitespacePolicy;
use line_diff::text_lines::TextLines;
use pretty_assertions::assert_eq;
use std::sync::Arc;

/// No name is bound: the runs of generated lines need none
struct NoBindings;

impl Bindings for NoBindings {
    fn names_at_within(&self, _: Grammar, _: &str, _: &[NameQuestion<'_>], _: usize) -> NamesAt {
        NamesAt::default()
    }

    fn resolution_work(&self, _: Grammar, tokens: usize) -> u64 {
        tokens as u64
    }
}

/// The regions of `text` as `name start..end`
fn regions(text: &str) -> Vec<String> {
    generated_regions(TextLines::of(text).all())
        .iter()
        .map(|region| format!("{} {}..{}", region.name, region.start, region.end))
        .collect()
}

/// The diff of `old` and `new` at `path` with the marks of the pair, its tokens read where the path has a grammar
fn marked(path: &str, old: &str, new: &str) -> (LineDiff, DiffMarks) {
    let policy = WhitespacePolicy::Default;
    let diff = diff_texts(old, new, policy, &DiffBudget::NONE);
    let grammar = pair_grammar(path, path);
    let read =
        |new_side: bool| grammar.and_then(|grammar| tokens(grammar, if new_side { new } else { old })).map(Arc::new);
    let pair = marks_of(&diff, old, new, grammar, policy, pair_indented(path, path), read, &NoBindings);
    (diff, pair.marks)
}

/// The runs of a diff as `old/new kind`, `*` for a quiet one, and its starts as `block:side:line`
fn shown(diff: &LineDiff, marks: &DiffMarks) -> (Vec<String>, Vec<String>, Vec<String>) {
    let kind = |kind: RunKind| match kind {
        RunKind::Formatting => "formatting",
        RunKind::Comments => "comments",
        RunKind::Renamed => "renamed",
        RunKind::Generated => "generated",
    };
    let blocks = diff
        .blocks
        .iter()
        .map(|block| format!("{}..{}/{}..{}", block.old_start, block.old_end, block.new_start, block.new_end))
        .collect();
    let runs = marks
        .runs
        .iter()
        .map(|run| {
            let quiet = if run.quiet { "*" } else { "" };
            format!("{}..{}/{}..{} {}{quiet}", run.old_start, run.old_end, run.new_start, run.new_end, kind(run.kind))
        })
        .collect();
    let starts =
        marks.starts.as_chunks::<3>().0.iter().map(|start| format!("{}:{}:{}", start[0], start[1], start[2])).collect();
    (blocks, runs, starts)
}

const START: &str = "### auto-generated section `build intellij.platform.core` start";
const END: &str = "### auto-generated section `build intellij.platform.core` end";

/// A Bazel file of a module: hand-written code around the region its generator writes from the `.iml`
fn build_file(hand: &str, deps: &[&str]) -> String {
    let deps: String = deps.iter().map(|dep| ["    \"", dep, "\",\n"].concat()).collect();
    format!(
        "load(\"@rules_jvm//:jvm.bzl\", \"jvm_library\")\n\n{START}\njvm_library(\n  name = \"core\",\n  deps = [\n{deps}  ],\n)\n{END}\n\n{hand}\n"
    )
}

/// Every form of a marker: the `###` of a Bazel generator, `//` with `@generated`, an HTML comment with its closer, a
/// block comment, `--`, `;` and a leading `*`, the words in any case, `begin` for `start`; the name is the text
/// between the leader and the last word, as written
#[test]
fn a_marker_is_a_comment_line_that_says_generated_and_ends_with_start_or_end() {
    let text = [
        START,
        "jvm_library()",
        END,
        "// @generated start",
        "fun a() = 1",
        "  // @generated end",
        "<!-- AUTO-GENERATED part start -->",
        "<tag/>",
        "<!-- AUTO-GENERATED part end -->",
        "/* Autogenerated: tables BEGIN */",
        "int x;",
        "/* Autogenerated: tables END */",
        "-- generated schema start",
        "-- generated schema end",
        "; regenerated keys start",
        "; regenerated keys end",
        " * Generated by hand start",
        " * Generated by hand end",
        "### auto-generated section 'maven libs' start",
        "### auto-generated section 'maven libs' end",
    ]
    .join("\n");
    assert_eq!(
        regions(&text),
        [
            "auto-generated section `build intellij.platform.core` 0..2",
            "@generated 3..5",
            "AUTO-GENERATED part 6..8",
            "Autogenerated: tables 9..11",
            "generated schema 12..13",
            "regenerated keys 14..15",
            "Generated by hand 16..17",
            "auto-generated section 'maven libs' 18..19",
        ]
    );
    // the lines strictly between the markers
    let found = generated_regions(TextLines::of(&text).all());
    assert_eq!(region_of(&found, 1).map(|region| region.start), Some(0));
    assert_eq!((region_of(&found, 0), region_of(&found, 2), region_of(&found, 13)), (None, None, None));
    assert_eq!(
        region_of(&found, 10),
        Some(&GeneratedRegion { name: "Autogenerated: tables".into(), start: 9, end: 11 })
    );
    assert!(found[0].holds(1) && !found[0].holds(0) && !found[0].holds(2));
}

/// A comment that says `generated` but ends with no `start` or `end`, a line that is no comment, a marker without
/// `generated`, and the line ends of the diff: `\r\n` and a lone `\r` end a line
#[test]
fn a_line_that_is_no_marker_makes_no_region_and_lines_end_as_the_diff_ends_them() {
    assert_eq!(regions("# generated by a tool\nx\n# generated by a tool, the end\n"), Vec::<String>::new());
    assert_eq!(regions("generated start\nx\ngenerated end\n"), Vec::<String>::new());
    assert_eq!(regions("# section start\nx\n# section end\n"), Vec::<String>::new());
    assert_eq!(regions("# generatedstart\n# generated end\n"), Vec::<String>::new());
    assert_eq!(regions("a\r\n# generated start\rx\r\n# generated end"), ["generated 1..3"]);
}

/// An end without a start, a start no end closes, an end of another region, and starts with another start between
/// them and their end: no region for them, and the regions around them stay
#[test]
fn an_unclosed_start_an_end_without_a_start_and_nested_starts_make_no_region() {
    // an end without a start, then a region
    assert_eq!(regions("# generated a end\n# generated a start\nx\n# generated a end\n"), ["generated a 1..3"]);
    // a start no end closes before a region: the region stays
    assert_eq!(regions("# generated a start\n# generated b start\nx\n# generated b end\n"), ["generated b 1..3"]);
    // an end of another name closes nothing
    assert_eq!(regions("# generated a start\nx\n# generated b end\n"), Vec::<String>::new());
    // a start inside another: neither is a region, and an end of the inner one leaves the outer one open
    assert_eq!(
        regions("# generated a start\n# generated b start\nx\n# generated b end\n# generated a end\n"),
        Vec::<String>::new()
    );
    // the same name twice: the end closes the nearest start, and the outer one, which no end closes, is none
    assert_eq!(regions("# generated a start\n# generated a start\nx\n# generated a end\n"), ["generated a 1..3"]);
    // closed too: both are nested
    assert_eq!(
        regions("# generated a start\n# generated a start\nx\n# generated a end\n# generated a end\n"),
        Vec::<String>::new()
    );
    // one after another
    assert_eq!(
        regions("# generated a start\nx\n# generated a end\n# generated a start\ny\n# generated a end\n"),
        ["generated a 0..2", "generated a 3..5"]
    );
}

/// A dependency added to the region, the old side of its block no line: a quiet run of generated lines, and the block
/// has nothing to read
#[test]
fn a_line_added_inside_a_region_is_a_quiet_run_and_its_block_has_no_start() {
    let (old, new) = (build_file("# mine", &["a", "c"]), build_file("# mine", &["a", "b", "c"]));
    let (diff, marks) = marked("lib/BUILD.bazel", &old, &new);
    assert_eq!(shown(&diff, &marks), (vec!["7..7/7..8".into()], vec!["7..7/7..8 generated*".into()], vec![]));
    // and removed: the new side no line
    let (diff, marks) = marked("lib/BUILD.bazel", &new, &old);
    assert_eq!(shown(&diff, &marks), (vec!["7..8/7..7".into()], vec!["7..8/7..7 generated*".into()], vec![]));
}

/// No grammar reads the file: the runs of generated lines are of its text alone
#[test]
fn a_pair_without_a_grammar_has_the_runs_of_its_generated_lines() {
    let (old, new) = (build_file("mine", &["a"]), build_file("mine", &["b"]));
    let (diff, marks) = marked("deps.unknown-extension", &old, &new);
    assert_eq!(shown(&diff, &marks), (vec!["6..7/6..7".into()], vec!["6..7/6..7 generated*".into()], vec![]));
}

/// A mixed change: the hand-written code outside the region is read, the region's lines are passed
#[test]
fn a_hand_written_line_outside_a_region_keeps_the_start_of_its_block() {
    let old = build_file("java_binary(name = \"tool\")", &["a"]);
    let new = build_file("java_binary(name = \"tool2\")", &["b"]);
    let (diff, marks) = marked("lib/BUILD.bazel", &old, &new);
    assert_eq!(
        shown(&diff, &marks),
        (vec!["6..7/6..7".into(), "11..12/11..12".into()], vec!["6..7/6..7 generated*".into()], vec!["1:1:11".into()])
    );
}

/// A region on one side alone (added, removed) and a region of another name on the other side (renamed): no run, and
/// every block is read
#[test]
fn a_region_on_one_side_alone_or_renamed_has_no_run() {
    let plain = "load(\"x\", \"y\")\n\njvm_library(\n  name = \"core\",\n)\n";
    let with = build_file("", &["a"]);
    let renamed = with.replace("platform.core", "platform.kernel");
    let changed = build_file("", &["b"]).replace("platform.core", "platform.kernel");
    for (old, new) in [(plain, with.as_str()), (with.as_str(), plain), (with.as_str(), changed.as_str())] {
        let (diff, marks) = marked("lib/BUILD.bazel", old, new);
        assert!(marks.runs.iter().all(|run| run.kind != RunKind::Generated), "{:?}", shown(&diff, &marks));
        assert_eq!(marks.starts.len() / 3, diff.blocks.len(), "{:?}", shown(&diff, &marks));
    }
    assert_ne!(renamed, with);
}

/// A block that holds a marker that changed and the lines of the region beside it: the lines inside are a run, the
/// marker is read, the reading starts at it
#[test]
fn a_block_across_a_marker_runs_only_its_lines_inside_the_region() {
    let old = format!("{START}\na\n{END}\nb\n");
    // the end marker gains trailing blanks: the same marker, another line to the diff
    let new = format!("{START}\nc\n{END}  \nb\n");
    let (diff, marks) = marked("x/BUILD.bazel", &old, &new);
    assert_eq!(
        shown(&diff, &marks),
        (vec!["1..3/1..3".into()], vec!["1..2/1..2 generated*".into()], vec!["0:1:2".into()])
    );
    // a line added before a changed end marker: the old side of the run is the place before the marker
    let new = format!("{START}\na\nc\n{END}  \nb\n");
    let (diff, marks) = marked("x/BUILD.bazel", &old, &new);
    assert_eq!(
        shown(&diff, &marks),
        (vec!["2..3/2..4".into()], vec!["2..2/2..3 generated*".into()], vec!["0:1:3".into()])
    );
}

/// A run of formatting inside the region is taken by the run of generated lines; one outside keeps its kind
#[test]
fn a_run_of_generated_lines_takes_the_lines_of_a_run_of_formatting() {
    let old = build_file("java_binary(name = \"tool\")", &["a"]);
    let new = build_file("java_binary( name = \"tool\" )", &["a"]).replace("    \"a\",", "    \"a\" ,");
    let (diff, marks) = marked("lib/BUILD.bazel", &old, &new);
    assert_eq!(
        shown(&diff, &marks),
        (
            vec!["6..7/6..7".into(), "11..12/11..12".into()],
            vec!["6..7/6..7 generated*".into(), "11..12/11..12 formatting*".into()],
            vec![]
        )
    );
}

/// A side of no lines at `p` is inside a region when `start < p && p <= end`: lines inserted right after the start
/// marker or right before the end marker are a run, lines inserted before the start marker or after the end marker
/// are none
#[test]
fn an_insertion_is_inside_a_region_between_its_markers() {
    let old = ["h", START, "a", END, "t", ""].join("\n");
    let inserted = |at: usize| {
        let mut lines: Vec<&str> = old.split('\n').collect();
        lines.insert(at, "x");
        lines.join("\n")
    };
    let runs = |at: usize| {
        let (diff, marks) = marked("x/BUILD.bazel", &old, &inserted(at));
        shown(&diff, &marks).1
    };
    // before the start marker (p = 1 = start), after it (p = 2), before the end marker (p = 3 = end), after it (p = 4)
    assert_eq!(runs(1), Vec::<String>::new());
    assert_eq!(runs(2), ["2..2/2..3 generated*"]);
    assert_eq!(runs(3), ["3..3/3..4 generated*"]);
    assert_eq!(runs(4), Vec::<String>::new());
}

/// The precedence, on runs alone: a run that shares a line with a run of generated lines, or stands across it on a
/// side, is dropped whole; one before it or after it on both sides stays, in the order of both sides
#[test]
fn a_run_that_meets_a_run_of_generated_lines_is_dropped_whole() {
    let run = |old: [u32; 2], new: [u32; 2], kind: RunKind| LineRun {
        old_start: old[0],
        old_end: old[1],
        new_start: new[0],
        new_end: new[1],
        kind,
        quiet: kind != RunKind::Comments,
    };
    let generated = vec![run([5, 5], [5, 7], RunKind::Generated)];
    let runs = vec![
        run([1, 3], [1, 3], RunKind::Formatting),
        // shares a new line
        run([4, 5], [4, 6], RunKind::Formatting),
        // its old side crosses the place of no lines
        run([4, 6], [8, 9], RunKind::Comments),
        // after it on both sides, at the same old line
        run([5, 6], [7, 8], RunKind::Comments),
    ];
    assert_eq!(
        with_generated(runs, generated),
        [
            run([1, 3], [1, 3], RunKind::Formatting),
            run([5, 5], [5, 7], RunKind::Generated),
            run([5, 6], [7, 8], RunKind::Comments)
        ]
    );
}
