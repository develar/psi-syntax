// Writes crates/csharp-syntax/src/unicode.rs: the character classes Roslyn's lexer asks of a UTF-16 code unit above
// ASCII (CharacterInfo.cs, UnicodeCharacterUtilities.cs at the Roslyn pin), decided by this runtime's
// CharUnicodeInfo.GetUnicodeCategory(char), the same call Roslyn makes, so the tables are the categories of the .NET
// the oracle runs on. The lexer reads UTF-16 code units: a supplementary character is two surrogates (category
// Surrogate), in none of the classes, so only 0x80..=0xFFFF is tabulated. ASCII is classified by the hand rules of
// UnicodeCharacterUtilities (written out here as 128-entry tables).
//
//   DOTNET_ROOT=$HOME/.cache/psi-syntax/dotnet $HOME/.cache/psi-syntax/dotnet/dotnet run --project tools/csharp-unicode \
//     > crates/csharp-syntax/src/unicode.rs
using System;
using System.Collections.Generic;
using System.Globalization;
using System.Text;

static class Program
{
    static bool IsLetter(UnicodeCategory c) => c is UnicodeCategory.UppercaseLetter or UnicodeCategory.LowercaseLetter
        or UnicodeCategory.TitlecaseLetter or UnicodeCategory.ModifierLetter or UnicodeCategory.OtherLetter
        or UnicodeCategory.LetterNumber;

    static bool IsPart(UnicodeCategory c) => IsLetter(c) || c is UnicodeCategory.DecimalDigitNumber
        or UnicodeCategory.ConnectorPunctuation or UnicodeCategory.NonSpacingMark
        or UnicodeCategory.SpacingCombiningMark or UnicodeCategory.Format;

    static void Ranges(StringBuilder o, string name, string doc, Func<UnicodeCategory, bool> member)
    {
        var ranges = new List<(int, int)>();
        int start = -1;
        for (int ch = 0x80; ch <= 0x10000; ch++)
        {
            bool m = ch <= 0xFFFF && member(CharUnicodeInfo.GetUnicodeCategory((char)ch));
            if (m && start < 0) start = ch;
            if (!m && start >= 0) { ranges.Add((start, ch - 1)); start = -1; }
        }
        o.Append($"/// {doc}\n");
        o.Append("#[rustfmt::skip]\n");
        o.Append($"pub(crate) static {name}: [(u16, u16); {ranges.Count}] = [\n");
        foreach (var (s, e) in ranges) o.Append($"    (0x{s:X4}, 0x{e:X4}),\n");
        o.Append("];\n\n");
    }

    static void Ascii(StringBuilder o, string name, string doc, Func<char, bool> member)
    {
        o.Append($"/// {doc}\n");
        o.Append("#[rustfmt::skip]\n");
        o.Append($"pub(crate) static {name}: [bool; 128] = [\n");
        for (int row = 0; row < 128; row += 16)
        {
            o.Append("   ");
            for (int ch = row; ch < row + 16; ch++) o.Append(member((char)ch) ? " true," : " false,");
            o.Append('\n');
        }
        o.Append("];\n\n");
    }

    static int Main()
    {
        var o = new StringBuilder();
        o.Append("//! The character classes of Roslyn's lexer (`CharacterInfo.cs`, `UnicodeCharacterUtilities.cs`) for a UTF-16 code\n");
        o.Append("//! unit: above ASCII sorted disjoint ranges of `CharUnicodeInfo.GetUnicodeCategory(char)`, as .NET ");
        o.Append(Environment.Version).Append(" answers it\n");
        o.Append("//! (the runtime of the oracle's SDK); ASCII by the hand rules of `UnicodeCharacterUtilities`. A surrogate is in none of\n");
        o.Append("//! them. Generated by `tools/csharp-unicode` (`Program.cs`); do not edit by hand.\n\n");
        Ascii(o, "ASCII_IDENTIFIER_START", "`IsIdentifierStartCharacter` below 0x80: `A-Z`, `a-z`, `_`.",
            ch => ch is >= 'A' and <= 'Z' or >= 'a' and <= 'z' or '_');
        Ascii(o, "ASCII_IDENTIFIER_PART", "`IsIdentifierPartCharacter` below 0x80: `A-Z`, `a-z`, `_`, `0-9`.",
            ch => ch is >= 'A' and <= 'Z' or >= 'a' and <= 'z' or '_' or >= '0' and <= '9');
        Ranges(o, "IDENTIFIER_START", "`IsIdentifierStartCharacter` above ASCII: `IsLetterChar` (Lu, Ll, Lt, Lm, Lo, Nl).", IsLetter);
        Ranges(o, "IDENTIFIER_PART",
            "`IsIdentifierPartCharacter` above ASCII: letter, decimal digit (Nd), connecting (Pc), combining (Mn, Mc), formatting (Cf).",
            IsPart);
        Ranges(o, "FORMATTING", "`IsFormattingChar` above ASCII (Cf): dropped from an identifier's value text.",
            c => c == UnicodeCategory.Format);
        Ranges(o, "SPACE_SEPARATOR", "`UnicodeCategory.SpaceSeparator` (Zs) above ASCII: `IsWhitespace` asks it for a char above 255.",
            c => c == UnicodeCategory.SpaceSeparator);
        Console.Out.Write(o.ToString().TrimEnd('\n') + "\n");
        return 0;
    }
}
